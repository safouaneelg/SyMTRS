"""Write a fingerprint of the dataset a set of runs was trained and scored on.

The SyMTRS dataset is being regenerated (AGENTS.md: "The dataset is under revision"), so a
number is only interpretable together with *which* capture produced it. This records, per
split and folder: file count, total bytes, image size of the first file, and a SHA-256 over
the sorted (name, size) list - cheap to compute and enough to tell two captures apart without
hashing gigabytes. It reads only names and sizes plus one image header per folder; it never
writes into the dataset.

    .venv/Scripts/python.exe scripts/dataset_manifest.py --data-root "<root>" --out docs/claude/DATASET.md
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
import struct
from pathlib import Path

SPLITS = ("train", "val", "test")


def image_size(path: Path) -> str:
    """Width x height from the header only (PNG IHDR, or the EXR dataWindow attribute)."""
    with path.open("rb") as fh:
        head = fh.read(4096)
    if head[:8] == b"\x89PNG\r\n\x1a\n":
        w, h = struct.unpack(">II", head[16:24])
        colour = {0: "gray", 2: "RGB", 4: "gray+A", 6: "RGBA"}.get(head[25], f"type{head[25]}")
        return f"{w}x{h} PNG {head[24]}-bit {colour}"
    if head[:4] == b"\x76\x2f\x31\x01":
        i = head.find(b"dataWindow\x00box2i\x00")
        if i >= 0:
            x0, y0, x1, y1 = struct.unpack("<iiii", head[i + 21:i + 37])
            return f"{x1 - x0 + 1}x{y1 - y0 + 1} EXR"
    return "?"


def folder_rows(split_dir: Path):
    for folder in sorted(p for p in split_dir.rglob("*") if p.is_dir()):
        files = sorted(f for f in folder.iterdir() if f.is_file())
        if not files:
            continue
        digest = hashlib.sha256()
        total = 0
        for f in files:
            size = f.stat().st_size
            total += size
            digest.update(f"{f.name}\t{size}\n".encode())
        yield (folder.relative_to(split_dir).as_posix(), len(files), total,
               image_size(files[0]), digest.hexdigest()[:16], files[0].name)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data-root", required=True)
    ap.add_argument("--out", default="docs/claude/DATASET.md")
    args = ap.parse_args()
    root = Path(args.data_root)

    lines = [
        "# Dataset used by the validation runs",
        "",
        f"Generated by `scripts/dataset_manifest.py` on {dt.datetime.now():%Y-%m-%d %H:%M}.",
        f"Root: `{root}`",
        "",
        "Only `train/`, `val/` and `test/` are used. The fingerprint is a SHA-256 over the sorted",
        "`name<TAB>size` list of each folder (first 16 hex digits): a different capture gives a",
        "different fingerprint.",
        "",
    ]
    log = root / "capture_log.txt"
    if log.exists():
        text = log.read_text(encoding="utf-8", errors="replace").splitlines()
        finished = [l for l in text if re.search(r"Capture finished", l)]
        lines += ["Capture log (`capture_log.txt`, outside the splits): " +
                  (f"`{finished[-1].strip()}`" if finished else "no 'Capture finished' line"),
                  f"(log modified {dt.datetime.fromtimestamp(log.stat().st_mtime):%Y-%m-%d %H:%M})", ""]
    summary = {}
    for split in SPLITS:
        split_dir = root / split
        lines += [f"## {split}", "", "| folder | files | MB | first file | size/format | fingerprint |",
                  "|---|---:|---:|---|---|---|"]
        for folder, n, total, size, fp, first in folder_rows(split_dir):
            lines.append(f"| `{folder}` | {n} | {total / 2**20:.0f} | `{first}` | {size} | `{fp}` |")
            summary[f"{split}/{folder}"] = {"files": n, "bytes": total, "fingerprint": fp}
        lines.append("")
    whole = hashlib.sha256(json.dumps(summary, sort_keys=True).encode()).hexdigest()[:16]
    lines.insert(4, f"**Dataset fingerprint: `{whole}`** (over all folders below).")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"dataset fingerprint {whole} -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
